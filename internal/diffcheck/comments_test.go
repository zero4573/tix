func TestCheckComments(t *testing.T) {
	dir := DiffCheckRepo(t)
	DiffCheckCommit(t, dir, "init", map[string][]byte{
		"a.go":   []byte("package a\n\n// moved from here\nfunc A() {}\n"),
		"b.go":   []byte("package a\n"),
		"doc.md": []byte("# doc\n"),
	})
	sha := DiffCheckCommit(t, dir, "change", map[string][]byte{
		"a.go":                []byte("package a\n\nfunc A() {}\n"),
		"b.go":                []byte("package a\n\n// moved from here\n\n// B does b\n// in two lines\n//go:noinline\nfunc B() {}\n"),
		"web/App.tsx":         []byte("// @ts-expect-error\nexport const x = 1 // trailing\n/**\n * the app\n */\n"),
		"lib/q.dart":          []byte("/// the queue\nclass Q {}\n"),
		"run.sh":              []byte("#!/bin/sh\n# runs it\necho hi\n"),
		"doc.md":              []byte("# doc\n// not code\n"),
		"testdata/fixture.go": []byte("// fixture comment\n"),
	})
	got, err := CheckComments(dir, sha)
	if err != nil {
		t.Fatal(err)
	}
	want := []CommentNote{{Path: "b.go", Lines: 2}, {Path: "lib/q.dart", Lines: 1}, {Path: "run.sh", Lines: 1}, {Path: "web/App.tsx", Lines: 2}}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("CheckComments = %+v, want %+v", got, want)
	}
}
