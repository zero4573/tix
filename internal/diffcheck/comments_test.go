func TestCommentText(t *testing.T) {
	for line, want := range map[string]string{
		"\t// retry twice because the API is flaky":               "// retry twice because the API is flaky",
		"  /* set below */":                                       "/* set below */",
		"   * the cache key":                                      "* the cache key",
		"{/* hidden until the flag ships */}":                     "/* hidden until the flag ships */}",
		"// eslint-disable-next-line react-hooks/exhaustive-deps": "// eslint-disable-next-line react-hooks/exhaustive-deps",
		"// @ts-expect-error":                                     "// @ts-expect-error",
		"//nolint:errcheck":                                       "//nolint:errcheck",
		"x := a // trailing comment":                              "",
		"const url = 'https://acme.test' // link":                 "",
		"total := a *":                                            "",
		"//go:build linux":                                        "",
		"//go:generate stringer -type=Kind":                       "",
		"// +build linux":                                         "",
		"/// <reference types=\"vite/client\" />":                 "",
		"// SPDX-License-Identifier: MIT":                         "",
		"// Copyright 2026 Acme":                                  "",
		"// Code generated by stringer; DO NOT EDIT.":             "",
		"// prettier-ignore":                                      "",
		"// see https://acme.test/issues/12":                      "",
		"/**":                                                     "",
		" */":                                                     "",
		" *":                                                      "",
		"//":                                                      "",
	} {
		if got := CommentText("a.ts", line); got != want {
			t.Errorf("CommentText(a.ts, %q) = %q, want %q", line, got, want)
		}
	}
}

func TestCommentTextByLanguage(t *testing.T) {
	for _, c := range []struct{ path, line, want string }{
		{"lib/queue.dart", "  /// Downloads with [load], in play [order]:", "/// Downloads with [load], in play [order]:"},
		{"lib/queue.dart", "  final job = _Job<T>(kind: kind);", ""},
		{"internal/cli/spec.go", "  * the vault, read-write, as the knowledge base", ""},
		{"internal/cli/spec.go", "/* a block */", "/* a block */"},
		{"web/a.ts", " * the cache key", "* the cache key"},
		{"scripts/run.sh", "# retry: the API is flaky", "# retry: the API is flaky"},
		{"scripts/run.sh", "#!/usr/bin/env bash", ""},
		{"scripts/run.sh", "# shellcheck shell=bash", ""},
		{"scripts/run.sh", "# shellcheck disable=SC2086", "# shellcheck disable=SC2086"},
		{"scripts/run.sh", "echo a # trailing", ""},
		{"modules/a.nix", "  # the slice bounds every sandbox", "# the slice bounds every sandbox"},
		{"app/main.py", "# -*- coding: utf-8 -*-", ""},
		{"app/main.py", "x = 1  # noqa", ""},
		{"app/main.py", "# noqa: E501", "# noqa: E501"},
		{"bitbucket-pipelines.yml", "  # runs on every push", "# runs on every push"},
		{"Dockerfile", "# syntax=docker/dockerfile:1", ""},
		{"Dockerfile.dev", "# the dev image", "# the dev image"},
		{"Makefile", "# see https://acme.test/issues/12", ""},
		{"Makefile", "########", ""},
		{"README.md", "# Title", ""},
		{"a.go", "# not a go comment", ""},
		{"a.py", "// not a python comment", ""},
	} {
		if got := CommentText(c.path, c.line); got != c.want {
			t.Errorf("CommentText(%s, %q) = %q, want %q", c.path, c.line, got, c.want)
		}
	}
}

